"""Diagnostic (a): how much of MPPI's label can a policy that sees only the state fit?

MPPI's label at a state depends on the state, on the warm-start plan it carries
in from earlier decisions, and on its random samples. At anchor states on
recorded episodes, MPPI is queried again with new planner seeds, under the
recorded warm start and under warm starts regenerated by replaying the episode
from its start with other planner seeds. Every replay executes the recorded
actions, so the physical state and solver warm-start at each anchor are the
recorded ones, bit for bit; only MPPI's internal history differs.

population "teacher": MPPI executes its action + N(0, exec_noise^2), as in
Step 15, so the anchors are states the Step 15 students learned from.
population "student": a saved policy executes its action + the same noise while
MPPI plans alongside on its states, as DAgger labels them.

Per anchor and action dimension, with W warm starts and R queries each:
    jitter     = mean_w Var_r(a)             sampling, warm start fixed
    warm_start = Var_w(mean_r a) - jitter/R  which warm start MPPI carries in
    floor      = jitter + warm_start         Var(a | state)
The mean floor is the lowest per-dimension MSE a policy that sees only the
state can reach on these labels, in the units of the students' fit loss.
Labels: "executed" is MPPI's own action (Step 15); "smoothed" re-weights the
same samples to n_eff/K = label_neff_fraction (Step 16).
"""
import hashlib
import json
import os
import subprocess
import time
from dataclasses import asdict, dataclass, replace
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import tyro

_REPO_ROOT = Path(__file__).resolve().parents[2]
POPULATIONS = ("teacher", "student")
LABELS = ("executed", "smoothed")
# Fit losses the students reached on these labels (docs/experiment_log.md).
FIT_LOSS = {"executed": 0.28, "smoothed": 0.255}
_FINGERPRINTED = ("configs/walker2d_best.json", "configs/walker2d_task.json", "src/mppi/mppi.py",
                  "src/envs/walker2d.py", "src/envs/mujoco_env.py", "scripts/diagnostics/label_variance_split.py")


@dataclass
class SplitConfig:
    populations: tuple[str, ...] = POPULATIONS
    episodes: int = 16
    anchors: int = 128
    # The recorded warm start plus regenerated ones.
    warm_starts: int = 9
    queries: int = 8
    K: int = 32
    H: int = 48
    steps: int = 400
    exec_noise: float = 0.1
    label_neff_fraction: float = 0.2
    student: str = "runs/2026-10-23_step15_teacher_seed0/policy_032.pt"
    seed_base: int = 7_000_000
    bootstrap: int = 2000
    workers: int = max(1, (os.cpu_count() or 2) - 2)


def _seeds(cfg: SplitConfig, population: str, episode: int) -> dict:
    base = cfg.seed_base + 10_000 * POPULATIONS.index(population) + episode
    return {"reset": base, "planner": base + 100_000, "noise": base + 200_000}


def _regenerated_seed(cfg: SplitConfig, population: str, episode: int, w: int) -> int:
    return cfg.seed_base + 300_000 + 10_000 * POPULATIONS.index(population) + 100 * episode + w


def _query_seed(cfg: SplitConfig, population: str, anchor: int, w: int, r: int) -> int:
    index = (anchor * cfg.warm_starts + w) * cfg.queries + r
    return cfg.seed_base + 1_000_000 + 100_000 * POPULATIONS.index(population) + index


def _planner_cfg(cfg: SplitConfig):
    from src.utils.config import MPPIConfig

    base = MPPIConfig(**json.loads((_REPO_ROOT / "configs/walker2d_best.json").read_text()))
    return replace(base, K=cfg.K, H=cfg.H)


def record_episode(cfg: SplitConfig, population: str, episode: int) -> dict:
    """One episode as Step 15 (teacher) or DAgger (student) collects it, with
    MPPI's state before every decision."""
    import torch

    from scripts.training.train_walker_mdgps import _walker
    from src.mppi.mppi import MPPI
    from src.rl.sac import load_policy

    torch.set_num_threads(1)
    seeds = _seeds(cfg, population, episode)
    env = _walker()
    planner = MPPI(env, _planner_cfg(cfg), seed=seeds["planner"])
    policy = None
    if population == "student":
        payload = torch.load(_REPO_ROOT / cfg.student, map_location="cpu", weights_only=False)
        policy = load_policy(payload.get("policy", payload))
    rng = np.random.default_rng(seeds["noise"])
    low, high = env.action_bounds
    np.random.seed(seeds["reset"])
    obs = env.reset()
    record = {key: [] for key in ("obs", "states", "warmstarts", "plans", "initial", "labels", "executed")}
    done = False
    for _ in range(cfg.steps):
        state, warmstart = env.get_state(), env.get_warmstart()
        snapshot = planner.snapshot()
        label, _ = planner.plan_step(state, initial_warmstart=warmstart)
        own = label if policy is None else policy.act(obs)
        action = np.clip(own + cfg.exec_noise * rng.standard_normal(env.action_dim), low, high)
        for key, value in (("obs", obs), ("states", state), ("warmstarts", warmstart), ("plans", snapshot["U"]),
                           ("initial", snapshot["initial_plan"]), ("labels", label), ("executed", action)):
            record[key].append(np.copy(value))
        obs, _, done, _ = env.step(action)
        if done:
            break
    data = {key: np.asarray(values) for key, values in record.items()}
    data.update(population=population, episode=episode, steps=len(record["labels"]), fell=bool(done))
    return data


def regenerate_warm_starts(cfg: SplitConfig, data: dict, times, seed: int) -> list[dict]:
    """MPPI's state before each decision in times, after replaying the episode's
    executed actions from its start with planner seed `seed`."""
    from scripts.training.train_walker_mdgps import _walker
    from src.mppi.mppi import MPPI

    env = _walker()
    planner = MPPI(env, _planner_cfg(cfg), seed=seed)
    env.reset(state=data["states"][0])
    env.set_warmstart(data["warmstarts"][0])
    wanted, found = {int(t) for t in times}, {}
    for t in range(max(wanted) + 1):
        state, warmstart = env.get_state(), env.get_warmstart()
        if not (np.array_equal(state, data["states"][t]) and np.array_equal(warmstart, data["warmstarts"][t])):
            raise RuntimeError(f"replay left the recorded trajectory at decision {t}")
        if t in wanted:
            found[t] = planner.snapshot()
            if t == max(wanted):
                break
        planner.plan_step(state, initial_warmstart=warmstart)
        env.step(data["executed"][t])
    return [found[int(t)] for t in times]


def query(cfg: SplitConfig, planner, state: np.ndarray, warmstart: np.ndarray, snapshot: dict) -> dict:
    """One decision from a planner snapshot: both labels and MPPI's final samples."""
    from scripts.training.train_walker_mdgps import _reweighted_label

    planner.restore(snapshot)
    label, info = planner.plan_step(state, initial_warmstart=warmstart)
    rollout = planner.get_rollout_data()
    return {"executed": label, "smoothed": _reweighted_label(rollout, cfg.label_neff_fraction),
            "n_eff": info["n_eff"], "first_actions": rollout["actions"][:, 0].copy(),
            "costs": rollout["costs"].copy()}


def _split(job: dict) -> dict:
    """Regenerate one episode's warm starts and query MPPI at its anchors."""
    from scripts.training.train_walker_mdgps import _walker
    from src.mppi.mppi import MPPI

    cfg, data, anchors = job["cfg"], job["episode"], job["anchors"]
    population, episode = data["population"], data["episode"]
    times = [t for _, t in anchors]
    warm = [[{"U": data["plans"][t], "initial_plan": bool(data["initial"][t])} for t in times]]
    for w in range(1, cfg.warm_starts):
        warm.append(regenerate_warm_starts(cfg, data, times, _regenerated_seed(cfg, population, episode, w)))
    planner = MPPI(_walker(), _planner_cfg(cfg), seed=0)
    out = {"anchor": [], "t": [], "decision_s": []}
    rows = []
    for j, (anchor, t) in enumerate(anchors):
        cell = []
        for w in range(cfg.warm_starts):
            for r in range(cfg.queries):
                rng_state = np.random.default_rng(_query_seed(cfg, population, anchor, w, r)).bit_generator.state
                started = time.perf_counter()
                cell.append(query(cfg, planner, data["states"][t], data["warmstarts"][t],
                                  {"U": warm[w][j]["U"], "initial_plan": warm[w][j]["initial_plan"],
                                   "rng_state": rng_state}))
                out["decision_s"].append(time.perf_counter() - started)
        rows.append(cell)
        out["anchor"].append(anchor)
        out["t"].append(t)
    shape = (len(anchors), cfg.warm_starts, cfg.queries)
    for key in ("executed", "smoothed", "n_eff", "first_actions", "costs"):
        out[key] = np.asarray([[q[key] for q in cell] for cell in rows]).reshape(*shape, *np.shape(rows[0][0][key]))
    out["warm_U"] = np.asarray([[warm[w][j]["U"] for w in range(cfg.warm_starts)] for j in range(len(anchors))])
    return out


def split_variance(labels: np.ndarray) -> dict[str, np.ndarray]:
    """labels (N, W, R, nu) -> per-anchor, per-dimension jitter, warm_start and floor."""
    R = labels.shape[2]
    jitter = labels.var(axis=2, ddof=1).mean(axis=1)
    warm_start = labels.mean(axis=2).var(axis=1, ddof=1) - jitter / R
    return {"jitter": jitter, "warm_start": warm_start, "floor": jitter + warm_start}


def _components(labels: np.ndarray) -> dict[str, float]:
    """Mean jitter, warm_start and floor, plus the state component and the
    share of label variance a state-only policy could explain."""
    W, R = labels.shape[1:3]
    parts = {key: float(value.mean()) for key, value in split_variance(labels).items()}
    anchor_means = labels.mean(axis=(1, 2))
    between = labels.mean(axis=2).var(axis=1, ddof=1)
    state = float((anchor_means.var(axis=0, ddof=1) - between.mean(axis=0) / W).mean())
    total = state + parts["floor"]
    return parts | {"state": state, "total": total, "explainable_share": state / total}


def _resamples(episodes: np.ndarray, n: int, seed: int):
    """Anchor indices for n resamples of whole episodes (anchors cluster by episode)."""
    rng = np.random.default_rng(seed)
    unique = np.unique(episodes)
    groups = [np.flatnonzero(episodes == e) for e in unique]
    for _ in range(n):
        yield np.concatenate([groups[i] for i in rng.integers(0, len(unique), len(unique))])


def _with_interval(point: dict, draws: list[dict]) -> dict:
    return {key: {"mean": value, "ci95": [float(np.percentile([d[key] for d in draws], q)) for q in (2.5, 97.5)]}
            for key, value in point.items()}


def _exchangeability(labels: np.ndarray, cost_min: np.ndarray) -> dict:
    """Is the recorded warm start one more draw from the regenerated ones?

    distance_ratio compares the recorded warm start's mean label with the
    regenerated ones against the regenerated ones among themselves (1 if
    exchangeable). min_cost_gap is the recorded warm start's mean lowest sample
    cost minus the regenerated ones' (negative: the regenerated plans are worse).
    """
    means = labels.mean(axis=2)
    W = means.shape[1]
    to_recorded = np.mean([(means[:, 0] - means[:, w]) ** 2 for w in range(1, W)])
    among = np.mean([(means[:, v] - means[:, w]) ** 2 for v in range(1, W) for w in range(v + 1, W)])
    costs = cost_min.mean(axis=2)
    return {"distance_ratio": float(to_recorded / among),
            "min_cost_gap": float(np.mean(costs[:, 0] - costs[:, 1:].mean(axis=1)))}


def report(cfg: SplitConfig, population: str, arrays: dict) -> dict:
    episodes, t = arrays["episode"], arrays["t"]
    seed = cfg.seed_base + 3_000_000 + POPULATIONS.index(population)
    out = {"anchors": int(len(t)), "episodes": int(len(np.unique(episodes))),
           "labels": {}, "subsets": {}}
    for label in LABELS:
        summary = _with_interval(_components(arrays[label]),
                                 [_components(arrays[label][i]) for i in _resamples(episodes, cfg.bootstrap, seed)])
        summary["floor_over_fit_loss"] = summary["floor"]["mean"] / FIT_LOSS[label]
        summary["at_action_bounds"] = float(np.mean(np.abs(arrays[label]) >= 0.999))
        out["labels"][label] = summary
    mature = t >= cfg.H
    subsets = {"t_below_H": ~mature, "t_at_least_H": mature}
    if population == "student":
        to_fall = arrays["steps"] - t
        subsets |= {"last_40_before_fall": arrays["fell"] & (to_fall <= 40),
                    "earlier": ~(arrays["fell"] & (to_fall <= 40))}
    for name, mask in subsets.items():
        if mask.sum() >= 2:
            out["subsets"][name] = {"anchors": int(mask.sum())} | {
                label: _components(arrays[label][mask]) for label in LABELS}
    # At the first decision every warm start is the zero plan.
    warm_differs = t > 0
    labels, costs = arrays["executed"][warm_differs], arrays["cost_min"][warm_differs]
    out["exchangeability"] = _with_interval(
        _exchangeability(labels, costs),
        [_exchangeability(labels[i], costs[i]) for i in _resamples(episodes[warm_differs], cfg.bootstrap, seed + 1)])
    out["median_neff_fraction"] = float(np.median(arrays["n_eff"]) / cfg.K)
    out["median_decision_s"] = float(np.median(arrays["decision_s"]))
    return out


def _provenance() -> dict:
    def git(*args):
        return subprocess.run(["git", *args], cwd=_REPO_ROOT, capture_output=True, text=True).stdout.strip()
    return {"commit": git("rev-parse", "HEAD"), "dirty": git("status", "--porcelain").splitlines(),
            "sha256": {path: hashlib.sha256((_REPO_ROOT / path).read_bytes()).hexdigest() for path in _FINGERPRINTED}}


def main(out_dir: Path, cfg: SplitConfig) -> None:
    if not cfg.populations or set(cfg.populations) - set(POPULATIONS):
        raise ValueError(f"populations must come from {POPULATIONS}; got {cfg.populations}.")
    if cfg.warm_starts < 2 or cfg.queries < 2:
        raise ValueError("The split needs at least two warm starts and two queries per anchor.")
    if cfg.episodes > 100 or cfg.warm_starts > 100 or cfg.anchors * cfg.warm_starts * cfg.queries > 100_000:
        raise ValueError("Seed blocks would overlap; reduce episodes, warm_starts or anchors.")
    if "student" in cfg.populations and not (_REPO_ROOT / cfg.student).exists():
        raise FileNotFoundError(f"missing student checkpoint {cfg.student}")
    out_dir.mkdir(parents=True, exist_ok=False)
    (out_dir / "config.json").write_text(json.dumps(asdict(cfg) | _provenance(), indent=2))
    started = time.time()
    with Pool(cfg.workers) as pool:
        recorded = pool.starmap(record_episode, [(cfg, p, e) for p in cfg.populations for e in range(cfg.episodes)])
        jobs = []
        for population in cfg.populations:
            episodes = [d for d in recorded if d["population"] == population]
            visited = [(i, t) for i, d in enumerate(episodes) for t in range(d["steps"])]
            if len(visited) < cfg.anchors:
                raise ValueError(f"{population}: only {len(visited)} visited states for {cfg.anchors} anchors.")
            rng = np.random.default_rng(cfg.seed_base + 2_000_000 + POPULATIONS.index(population))
            chosen = sorted(rng.choice(len(visited), size=cfg.anchors, replace=False))
            for i, data in enumerate(episodes):
                anchors = [(a, visited[c][1]) for a, c in enumerate(chosen) if visited[c][0] == i]
                if anchors:
                    jobs.append({"cfg": cfg, "episode": data, "anchors": anchors})
        # Longest replays first keeps the pool busy.
        jobs.sort(key=lambda job: -max(t for _, t in job["anchors"]))
        results = pool.map(_split, jobs)
    result = {"wall_time_s": time.time() - started, "fit_loss": FIT_LOSS, "populations": {}}
    raw = {}
    for population in cfg.populations:
        parts = [(job, res) for job, res in zip(jobs, results) if job["episode"]["population"] == population]
        order = np.argsort(np.concatenate([res["anchor"] for _, res in parts]))
        cat = lambda key: np.concatenate([res[key] for _, res in parts])[order]
        per_anchor = lambda key: np.concatenate([[job["episode"][key]] * len(res["anchor"])
                                                 for job, res in parts])[order]
        arrays = {key: cat(key) for key in ("t", "executed", "smoothed", "n_eff", "first_actions",
                                             "costs", "warm_U")}
        arrays |= {"episode": per_anchor("episode"), "steps": per_anchor("steps"), "fell": per_anchor("fell"),
                   "cost_min": cat("costs").min(axis=-1),
                   "decision_s": np.concatenate([res["decision_s"] for _, res in parts])}
        arrays["recorded_label"] = np.asarray([job["episode"]["labels"][t] for job, res in parts
                                               for t in res["t"]])[order]
        arrays["obs"] = np.asarray([job["episode"]["obs"][t] for job, res in parts for t in res["t"]])[order]
        episodes = [d for d in recorded if d["population"] == population]
        result["populations"][population] = report(cfg, population, arrays) | {
            "episode_steps": [int(d["steps"]) for d in episodes], "falls": int(sum(d["fell"] for d in episodes))}
        raw |= {f"{population}_{key}": value for key, value in arrays.items()}
    np.savez_compressed(out_dir / "raw.npz", **raw)
    (out_dir / "report.json").write_text(json.dumps(result, indent=2))
    for population, summary in result["populations"].items():
        for label in LABELS:
            parts = summary["labels"][label]
            print(population, label, {key: round(parts[key]["mean"], 4)
                                      for key in ("jitter", "warm_start", "floor", "state", "explainable_share")})


if __name__ == "__main__":
    tyro.cli(main)
