"""Step 29: does pulling MPPI toward a student that learned MPPI's own average
tie MPPI's action to the state? No training.

MPPI (frozen config except K and H) keeps its own warm start and its own
samples. For each alpha its score adds the network-matching term of
src/gps/policy_matching.py toward a fixed student (alpha = 0 is raw MPPI).

Walking: episodes of `walk_steps` controls from development resets with no
action noise, as in Steps 18 and 25.
Labels: teacher episodes recorded as in Step 22 (MPPI executes its action plus
N(0, exec_noise^2)), with the term on throughout. At anchor decisions MPPI is
queried again, `queries` times each, under the recorded warm start and under
warm starts regenerated by replaying the episode's executed actions with other
planner seeds. The split into jitter, warm start, floor and the state's share
of the label variance follows scripts/diagnostics/label_variance_split.py.
"""
import json
from dataclasses import replace
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import tyro

from scripts.diagnostics.label_variance_split import _components, _resamples, _with_interval

_REPO_ROOT = Path(__file__).resolve().parents[2]
STEP15_STUDENT = "runs/2026-10-23_step15_teacher_seed0/policy_032.pt"


def _student(path: str):
    import torch

    from src.rl.sac import load_policy

    payload = torch.load(_REPO_ROOT / path, map_location="cpu", weights_only=False)
    actor = load_policy(payload.get("policy", payload), device="cpu")

    @torch.no_grad()
    def act_batch(obs: np.ndarray) -> np.ndarray:
        mean, _ = actor(torch.as_tensor(np.atleast_2d(obs), dtype=torch.float32))
        return (torch.tanh(mean) * actor.action_scale + actor.action_bias).numpy().astype(float)

    return act_batch


def _setup(job: dict, seed: int):
    import torch

    from src.envs.walker2d import Walker2d
    from src.gps.policy_matching import PolicyMatching
    from src.mppi.mppi import MPPI
    from src.utils.config import MPPIConfig

    torch.set_num_threads(1)
    env = Walker2d(**json.loads((_REPO_ROOT / "configs/walker2d_task.json").read_text()), nthread=1)
    base = MPPIConfig(**json.loads((_REPO_ROOT / "configs/walker2d_best.json").read_text()))
    planner = MPPI(env, replace(base, K=job["K"], H=job["H"]), seed=seed)
    act = _student(job["student"])
    matching = PolicyMatching(env, act, job["alpha"]) if job["alpha"] > 0 else None
    return env, planner, matching, act


def _plan(planner, matching, state: np.ndarray, warmstart: np.ndarray) -> np.ndarray:
    if matching is not None:
        matching.state = state
    return planner.plan_step(state, prior_cost=matching, initial_warmstart=warmstart)[0]


def walk(job: dict) -> dict:
    env, planner, matching, _ = _setup(job, job["planner_seed"])
    np.random.seed(job["reset_seed"])
    env.reset()
    velocities, survived = [], True
    for _ in range(job["steps"]):
        _, _, done, info = env.step(_plan(planner, matching, env.get_state(), env.get_warmstart()))
        velocities.append(info["x_velocity"])
        if done:
            survived = False
            break
    return {"kind": "walk", "alpha": job["alpha"], "reset_seed": job["reset_seed"], "steps": len(velocities),
            "survived": survived, "velocity_mae": float(np.mean(np.abs(env._v_target - np.asarray(velocities))))}


def labels(job: dict) -> dict:
    """Record one teacher episode with the term on, then query MPPI at its anchors."""
    env, planner, matching, act = _setup(job, job["planner_seed"])
    rng = np.random.default_rng(job["noise_seed"])
    low, high = env.action_bounds
    np.random.seed(job["reset_seed"])
    obs = env.reset()
    rec = {key: [] for key in ("obs", "states", "warmstarts", "plans", "initial", "executed")}
    done = False
    for _ in range(job["steps"]):
        state, warmstart = env.get_state(), env.get_warmstart()
        snapshot = planner.snapshot()
        label = _plan(planner, matching, state, warmstart)
        action = np.clip(label + job["exec_noise"] * rng.standard_normal(env.action_dim), low, high)
        for key, value in (("obs", obs), ("states", state), ("warmstarts", warmstart), ("plans", snapshot["U"]),
                           ("initial", snapshot["initial_plan"]), ("executed", action)):
            rec[key].append(np.copy(value))
        obs, _, done, _ = env.step(action)
        if done:
            break
    rec = {key: np.asarray(value) for key, value in rec.items()}
    decisions = len(rec["executed"])
    count = min(job["anchors"], decisions - 1)
    times = np.sort(np.random.default_rng(job["anchor_seed"]).choice(np.arange(1, decisions), count, replace=False))
    warm = [[{"U": rec["plans"][t], "initial_plan": bool(rec["initial"][t])} for t in times]]
    for w in range(1, job["warm_starts"]):
        replay_env, replay, replay_matching, _ = _setup(job, job["regen_seed"] + w)
        replay_env.reset(state=rec["states"][0])
        replay_env.set_warmstart(rec["warmstarts"][0])
        found = {}
        for t in range(int(times[-1]) + 1):
            state, warmstart = replay_env.get_state(), replay_env.get_warmstart()
            if not (np.array_equal(state, rec["states"][t]) and np.array_equal(warmstart, rec["warmstarts"][t])):
                raise RuntimeError(f"replay left the recorded trajectory at decision {t}")
            if t in times:
                found[t] = replay.snapshot()
            _plan(replay, replay_matching, state, warmstart)
            replay_env.step(rec["executed"][t])
        warm.append([found[int(t)] for t in times])
    _, query, query_matching, _ = _setup(job, 0)
    out = np.empty((count, job["warm_starts"], job["queries"], env.action_dim))
    for j, t in enumerate(times):
        for w in range(job["warm_starts"]):
            for r in range(job["queries"]):
                rng_state = np.random.default_rng(job["query_seed"] + (j * job["warm_starts"] + w) * job["queries"]
                                                  + r).bit_generator.state
                query.restore({"U": warm[w][j]["U"], "initial_plan": warm[w][j]["initial_plan"],
                               "rng_state": rng_state})
                out[j, w, r] = _plan(query, query_matching, rec["states"][t], rec["warmstarts"][t])
    student = act(rec["obs"][times])
    return {"kind": "labels", "alpha": job["alpha"], "episode": job["episode"], "t": times, "labels": out,
            "fell": bool(done), "decisions": decisions,
            "gap_to_student": float(np.mean((out - student[:, None, None, :]) ** 2))}


def _run(job: dict) -> dict:
    return walk(job) if job["kind"] == "walk" else labels(job)


def main(
    out_dir: Path,
    alphas: tuple[float, ...] = (0.0, 1.0, 3.0, 10.0),
    student: str = STEP15_STUDENT,
    label_episodes: int = 8,
    anchors: int = 8,
    warm_starts: int = 5,
    queries: int = 4,
    steps: int = 400,
    exec_noise: float = 0.1,
    walk_episodes: int = 20,
    walk_steps: int = 1000,
    walk_reset_seed: int = 70_000,
    walk_planner_seed: int = 95_000,
    seed_base: int = 8_000_000,
    K: int = 32,
    H: int = 48,
    bootstrap: int = 1000,
    workers: int = 24,
) -> None:
    if 0.0 not in alphas:
        raise ValueError("alphas must include 0, raw MPPI.")
    common = {"student": student, "K": K, "H": H}
    jobs = [{**common, "kind": "labels", "alpha": a, "episode": e, "steps": steps, "exec_noise": exec_noise,
             "anchors": anchors, "warm_starts": warm_starts, "queries": queries,
             "reset_seed": seed_base + e, "planner_seed": seed_base + 100_000 + e,
             "noise_seed": seed_base + 200_000 + e, "regen_seed": seed_base + 300_000 + 100 * e,
             "anchor_seed": seed_base + 400_000 + e, "query_seed": seed_base + 1_000_000 + 10_000 * e}
            for a in alphas for e in range(label_episodes)]
    jobs += [{**common, "kind": "walk", "alpha": a, "steps": walk_steps, "reset_seed": walk_reset_seed + e,
              "planner_seed": walk_planner_seed + e} for a in alphas for e in range(walk_episodes)]
    out_dir.mkdir(parents=True, exist_ok=False)
    with Pool(workers) as pool:
        rows = pool.map(_run, jobs)
    result = {"student": student, "alphas": list(alphas), "arms": {}}
    arrays = {}
    for a in alphas:
        walks = [r for r in rows if r["kind"] == "walk" and r["alpha"] == a]
        cells = [r for r in rows if r["kind"] == "labels" and r["alpha"] == a]
        stacked = np.concatenate([r["labels"] for r in cells])
        episodes = np.concatenate([np.full(len(r["t"]), r["episode"]) for r in cells])
        arrays[f"alpha_{a:g}"] = stacked
        split = _with_interval(_components(stacked),
                               [_components(stacked[i]) for i in _resamples(episodes, bootstrap, seed_base + 9)])
        result["arms"][f"{a:g}"] = {
            "walk": {"completed": sum(r["survived"] for r in walks), "episodes": len(walks),
                     "mean_seconds_alive": float(np.mean([r["steps"] for r in walks]) * 0.008),
                     "velocity_mae": float(np.mean([r["velocity_mae"] for r in walks])),
                     "per_episode": [[r["reset_seed"], r["steps"], r["survived"]] for r in walks]},
            "labels": {"anchors": int(len(stacked)), "label_episodes_fell": sum(r["fell"] for r in cells),
                       "gap_to_student": float(np.mean([r["gap_to_student"] for r in cells])), **split}}
    np.savez_compressed(out_dir / "labels.npz", **arrays)
    (out_dir / "summary.json").write_text(json.dumps(result, indent=2))
    for a, arm in result["arms"].items():
        lab = arm["labels"]
        print(f"alpha {a}: walk {arm['walk']['completed']}/{arm['walk']['episodes']} "
              f"alive {arm['walk']['mean_seconds_alive']:.2f} s MAE {arm['walk']['velocity_mae']:.3f} | "
              f"floor {lab['floor']['mean']:.3f} {lab['floor']['ci95']} share {lab['explainable_share']['mean']:.3f} "
              f"{lab['explainable_share']['ci95']} gap to student {lab['gap_to_student']:.3f}")


if __name__ == "__main__":
    tyro.cli(main)
